#include "io/output/XYZWriter.h"

#include <fstream>
#include <iomanip>
#include <sstream>
#include <utility>

namespace io {

XYZWriter::XYZWriter(int output_interval_arg, std::string filename)
    : OutputWriter(output_interval_arg), output_filename(std::move(filename)) {}

void XYZWriter::onStep(const ParticleContainer &particles, int iteration, double time [[maybe_unused]]) {
    if (iteration % output_interval != 0) {
        return;
    }
    std::ofstream file;
    std::stringstream strstr;
    strstr << output_filename << "_" << std::setfill('0') << std::setw(4) << iteration / output_interval << ".xyz";

    file.open(strstr.str().c_str());
    file << particles.size() << std::endl;
    file << "Generated by MolSim. See http://openbabel.org/wiki/XYZ_(format) for "
            "file format doku."
         << std::endl;

    for (auto &p : particles) {
        std::array<double, 3> x = p.getX();
        file << "Ar ";
        file.setf(std::ios_base::showpoint);

        for (auto &xi : x) {
            file << xi << " ";
        }

        file << std::endl;
    }

    file.close();
}

}  // namespace io
