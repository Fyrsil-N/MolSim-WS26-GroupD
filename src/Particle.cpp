#include "Particle.h"

#include <spdlog/spdlog.h>

#include <iostream>

#include "utils/ArrayUtils.h"

Particle::Particle(int type_arg) : f({0., 0., 0.}), old_f({0., 0., 0.}), type(type_arg) {
    // Used info here, since this information is not critical to the user
    spdlog::info("Particle generated!");
}

Particle::Particle(const Particle &other)
    : x(other.x), v(other.v), f(other.f), old_f(other.old_f), m(other.m), type(other.type) {
    // Used info here, since this information is not critical to the user
    spdlog::info("Particle generated by copy!");
}

Particle::Particle(const std::array<double, 3> &x_arg, const std::array<double, 3> &v_arg, double m_arg, int type_arg)
    : x(x_arg), v(v_arg), f({0., 0., 0.}), old_f({0., 0., 0.}), m(m_arg), type(type_arg) {
    // Used info here, since this information is not critical to the user
    spdlog::info("Particle generated!");
}

Particle::~Particle() {
    // Used info here, since this information is not critical to the user
    spdlog::info("Particle destructed!");
}

const std::array<double, 3> &Particle::getX() const { return x; }

const std::array<double, 3> &Particle::getV() const { return v; }

const std::array<double, 3> &Particle::getF() const { return f; }

const std::array<double, 3> &Particle::getOldF() const { return old_f; }

double Particle::getM() const { return m; }

int Particle::getType() const { return type; }

void Particle::setX(const std::array<double, 3> &x_arg) { x = x_arg; }

void Particle::setV(const std::array<double, 3> &v_arg) { v = v_arg; }

void Particle::setF(const std::array<double, 3> &f_arg) { f = f_arg; }

void Particle::setOldF(const std::array<double, 3> &old_f_arg) { old_f = old_f_arg; }

void Particle::resetF() {
    old_f = f;
    f = std::array<double, 3>{0., 0., 0.};
}

void Particle::addToF(const std::array<double, 3> &delta_f) { f = f + delta_f; }

std::string Particle::toString() const {
    std::stringstream stream;
    stream << "Particle: X:" << x << " v: " << v << " f: " << f << " old_f: " << old_f << " type: " << type;
    return stream.str();
}

bool Particle::operator==(const Particle &other) const {
    return (x == other.x) and (v == other.v) and (f == other.f) and (type == other.type) and (m == other.m) and
           (old_f == other.old_f);
}

double Particle::distanceTo(const Particle &other) const {
    const auto diff = this->getX() - other.getX();
    return std::max(ArrayUtils::L2Norm(diff), std::numeric_limits<double>::denorm_min());
}

std::ostream &operator<<(std::ostream &stream, Particle &p) {
    stream << p.toString();
    return stream;
}
